"""One publishing run: build today's article, attach a photo, commit, push."""
from __future__ import annotations

import importlib.util
import json
import shutil
import subprocess
from datetime import datetime
from pathlib import Path
from zoneinfo import ZoneInfo

from . import config, writer


def load_daily_blog():
    """Import scripts/daily_blog.py from the mounted repository."""
    path = config.SITE_ROOT / "scripts" / "daily_blog.py"
    spec = importlib.util.spec_from_file_location("daily_blog", path)
    if spec is None or spec.loader is None:
        raise RuntimeError(f"cannot load {path}")
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def today_jst() -> str:
    return datetime.now(ZoneInfo("Asia/Tokyo")).date().isoformat()


def write_today(date: str) -> bool:
    """Let Claude write today's article. False means the written rotation is used.

    Runs before daily_blog.generate(): that function only inserts a rotation tip
    when the day has no article yet, so putting the LLM article in first makes
    generate() rebuild the pages around it instead of competing with it.
    """
    data = json.loads(config.POSTS_FILE.read_text(encoding="utf-8"))
    posts = data.get("posts", [])
    if any(post.get("date") == date for post in posts):
        print(f"[LLM] {date} already has an article")
        return False
    article = writer.write_article(date, [str(p.get("title", "")) for p in posts[:20]])
    if not article:
        return False
    daily_blog = load_daily_blog()
    stamp = datetime.strptime(date, "%Y-%m-%d").strftime("%Y年%m月%d日")
    posts.insert(0, {
        "id": date + "-daily-football",
        "date": date,
        "category": article["category"],
        "visual": "DAILY",
        "title": stamp + "のYSCC観戦ノート｜" + article["title"],
        "summary": article["summary"],
        "body": list(article["body"]) + [
            "次の週末に行ける試合がないか、JFL公式日程とY.S.C.C.公式チケットサイトをチェックしてみましょう。"
            "開催情報や販売条件は公式の最新情報が優先です。"
        ],
        "sources": [
            {"label": "JFL公式 試合日程", "url": daily_blog.JFL},
            {"label": "Y.S.C.C.公式チケット", "url": daily_blog.TICKET},
        ],
        "autoGenerated": True,
        "writer": writer.MODEL,
    })
    config.POSTS_FILE.write_text(
        json.dumps({"posts": posts}, ensure_ascii=False, indent=2) + "\n", encoding="utf-8"
    )
    return True


def attach_photo(date: str) -> bool:
    """Give the day's article a hero photo. Returns True if posts.json changed."""
    if not config.drive_configured():
        print(f"[PHOTO] skipped: {config.drive_status()}")
        return False
    data = json.loads(config.POSTS_FILE.read_text(encoding="utf-8"))
    posts = data.get("posts", [])
    target = next((p for p in posts if p.get("date") == date), None)
    if target is None:
        print(f"[PHOTO] no article dated {date}")
        return False
    if target.get("hero"):
        print(f"[PHOTO] {target['id']} already has a hero photo")
        return False
    try:
        from . import drive_photos
        hero = drive_photos.fetch_photo_for(date)
    except Exception as error:  # a Drive outage must not stop the text article
        print(f"[PHOTO] Drive failed, publishing without a photo: {error}")
        return False
    if not hero:
        return False
    target["hero"] = hero
    config.POSTS_FILE.write_text(
        json.dumps({"posts": posts}, ensure_ascii=False, indent=2) + "\n", encoding="utf-8"
    )
    return True


# 公開してよいものだけを site/ に置く。リポジトリをそのまま配ると
# https://.../.env でAPIキーとDrive設定が読めてしまう。拒否リストではなく
# 許可リストにしているのは、新しいファイルが増えたときに漏れないようにするため。
PUBLIC_FILES = ("index.html", "app.js", "styles.css", "football.css",
                "favicon.svg", "robots.txt", "sitemap.xml", ".nojekyll")
PUBLIC_DIRS = ("blog", "data", "assets")


def export_site() -> Path:
    """Copy the public subset into site/ and return that directory."""
    target = config.SITE_EXPORT_DIR
    target.mkdir(parents=True, exist_ok=True)
    for name in PUBLIC_FILES:
        source = config.SITE_ROOT / name
        if source.exists():
            shutil.copyfile(source, target / name)
    for name in PUBLIC_DIRS:
        source = config.SITE_ROOT / name
        if not source.is_dir():
            continue
        destination = target / name
        if destination.exists():
            shutil.rmtree(destination)
        shutil.copytree(source, destination)
    print(f"[SITE] exported {target}")
    return target


def git(*args: str) -> subprocess.CompletedProcess:
    return subprocess.run(
        ["git", "-C", str(config.SITE_ROOT), *args],
        check=True, capture_output=True, text=True,
    )


def commit_and_push(date: str) -> None:
    if not config.GIT_PUSH:
        print("[GIT] GIT_PUSH is off; changes are left in the working tree")
        return
    git("config", "user.name", config.GIT_AUTHOR_NAME)
    git("config", "user.email", config.GIT_AUTHOR_EMAIL)
    git("add", "data", "blog", "sitemap.xml", "robots.txt", "assets")
    staged = subprocess.run(
        ["git", "-C", str(config.SITE_ROOT), "diff", "--cached", "--quiet"]
    )
    if staged.returncode == 0:
        print("[GIT] nothing new to publish today")
        return
    git("commit", "-m", f"content: publish BLUE COURT daily journal {date}")
    git("push", config.GIT_REMOTE, f"HEAD:{config.GIT_BRANCH}")
    print(f"[GIT] pushed to {config.GIT_REMOTE}/{config.GIT_BRANCH}")


def publish_once() -> str:
    date = today_jst()
    print(f"[RUN] BLUE COURT publish for {date} (JST)")
    write_today(date)              # Claude writes it, or leaves it to the rotation
    daily_blog = load_daily_blog()
    daily_blog.generate()          # fall back to the written rotation, rebuild pages
    if attach_photo(date):
        daily_blog.generate()      # rebuild pages so the photo is rendered
    export_site()
    commit_and_push(date)
    return date
